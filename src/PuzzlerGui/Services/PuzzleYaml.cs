using System.Globalization;
using System.Text;
using PuzzlerGui.Models;
using YamlDotNet.Core;
using YamlDotNet.RepresentationModel;

namespace PuzzlerGui.Services;

/// <summary>Reads and writes the tiny YAML dialect used by <c>.pzle</c> files.</summary>
public static class PuzzleYaml
{
    public static PuzzleDocument Load(string text)
    {
        var stream = new YamlStream();
        try
        {
            stream.Load(new StringReader(text));
        }
        catch (Exception ex) when (ex is YamlException or InvalidOperationException)
        {
            throw new PuzzleFormatException($"invalid YAML: {ex.Message}", ex);
        }

        if (stream.Documents.Count == 0)
        {
            throw new PuzzleFormatException("the document is empty");
        }

        var root = stream.Documents[0].RootNode;
        if (root is not YamlMappingNode rootMap)
        {
            throw new PuzzleFormatException("the document must be a YAML mapping");
        }

        YamlNode puzzleNode;
        if (TryGet(rootMap, "puzzle", out var wrapped))
        {
            puzzleNode = wrapped;
        }
        else if (TryGet(rootMap, "pieces", out _))
        {
            puzzleNode = rootMap;
        }
        else
        {
            throw new PuzzleFormatException("missing the top-level `puzzle:` section");
        }

        var map = NormalizeMapping(puzzleNode, "puzzle");

        var name = "puzzle";
        if (TryGet(map, "name", out var nameNode))
        {
            name = RequireScalar(nameNode, "puzzle.name");
        }

        var boardNode = GetAny(map, "board_shape", "board")
            ?? throw new PuzzleFormatException("puzzle: missing `board_shape:`");
        var boardText = ShapeText(boardNode, "puzzle.board_shape");
        var board = ParseBoard(boardText);

        var allUse = GetBool(map, "all_use", true);
        var canFlip = GetBool(map, "can_flip", "flip", false);
        var canRotate = GetBool(map, "can_rotate", "rotate", false);

        var piecesNode = TryGet(map, "pieces", out var piecesValue)
            ? piecesValue
            : throw new PuzzleFormatException("puzzle: missing the `pieces:` list");
        if (piecesNode is not YamlSequenceNode pieceEntries)
        {
            throw new PuzzleFormatException("puzzle.pieces: a list of pieces is required");
        }

        var document = new PuzzleDocument(name, board)
        {
            AllUse = allUse,
            CanRotate = canRotate,
            CanFlip = canFlip,
        };

        for (var index = 0; index < pieceEntries.Children.Count; index++)
        {
            var context = $"piece #{index + 1}";
            var entry = NormalizeMapping(pieceEntries.Children[index], context);

            var id = (index + 1).ToString(CultureInfo.InvariantCulture);
            if (TryGet(entry, "id", out var idNode))
            {
                id = RequireScalar(idNode, $"{context}.id");
            }

            var shapeNode = TryGet(entry, "shape", out var shapeValue)
                ? shapeValue
                : throw new PuzzleFormatException($"{context}: missing `shape:`");
            var shape = ShapeModel.FromText(ShapeText(shapeNode, $"{context}.shape"));

            var count = 1;
            if (TryGet(entry, "count", out var countNode))
            {
                count = ParseInt(RequireScalar(countNode, $"{context}.count"), $"{context}.count");
                if (count < 1 || count > ushort.MaxValue)
                {
                    throw new PuzzleFormatException($"{context}: count must be between 1 and {ushort.MaxValue}");
                }
            }

            var rotateOverride = GetTriState(entry, "can_rotate", "rotate");
            var flipOverride = GetTriState(entry, "can_flip", "flip");

            document.Pieces.Add(new PieceModel(id, shape, count)
            {
                CanRotate = rotateOverride,
                CanFlip = flipOverride,
            });
        }

        return document;
    }

    public static string Save(PuzzleDocument document)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Generated by puzzler-gui");
        builder.AppendLine("puzzle:");
        builder.Append("  name: ").AppendLine(Quote(document.Name));
        builder.Append("  all_use: ").AppendLine(document.AllUse ? "true" : "false");
        builder.Append("  can_rotate: ").AppendLine(document.CanRotate ? "true" : "false");
        builder.Append("  can_flip: ").AppendLine(document.CanFlip ? "true" : "false");

        var boardRows = TrimmedBoardRows(document.Board);
        if (document.Board.AllPlayable)
        {
            builder.Append("  board_shape: rectangle{")
                .Append(document.Board.Width)
                .Append(',')
                .Append(document.Board.Height)
                .AppendLine("}");
        }
        else
        {
            builder.AppendLine("  board_shape: |");
            foreach (var row in boardRows)
            {
                builder.Append("    ").AppendLine(row);
            }
        }

        builder.AppendLine("  pieces:");
        foreach (var piece in document.Pieces)
        {
            var shape = piece.Shape.Clone();
            shape.Trim();
            var rows = shape.ToRows();

            builder.Append("    - id: ").AppendLine(Quote(piece.Id));
            builder.AppendLine("      shape: |");
            foreach (var row in rows)
            {
                builder.Append("        ").AppendLine(row);
            }

            if (piece.Count != 1)
            {
                builder.Append("      count: ").AppendLine(piece.Count.ToString(CultureInfo.InvariantCulture));
            }

            if (piece.CanRotate != TriState.Inherit)
            {
                builder.Append("      can_rotate: ")
                    .AppendLine(piece.CanRotate == TriState.Allow ? "true" : "false");
            }

            if (piece.CanFlip != TriState.Inherit)
            {
                builder.Append("      can_flip: ")
                    .AppendLine(piece.CanFlip == TriState.Allow ? "true" : "false");
            }
        }

        return builder.ToString();
    }

    private static string[] TrimmedBoardRows(BoardModel board)
    {
        var rows = board.ToAsciiRows();
        var minRow = int.MaxValue;
        var maxRow = -1;
        var minCol = int.MaxValue;
        var maxCol = -1;
        for (var row = 0; row < rows.Length; row++)
        {
            for (var col = 0; col < rows[row].Length; col++)
            {
                if (rows[row][col] != '#')
                {
                    continue;
                }

                minRow = Math.Min(minRow, row);
                maxRow = Math.Max(maxRow, row);
                minCol = Math.Min(minCol, col);
                maxCol = Math.Max(maxCol, col);
            }
        }

        if (maxRow < 0)
        {
            return new[] { "." };
        }

        var trimmed = new string[maxRow - minRow + 1];
        for (var row = minRow; row <= maxRow; row++)
        {
            trimmed[row - minRow] = rows[row].Substring(minCol, maxCol - minCol + 1);
        }

        return trimmed;
    }

    private static BoardModel ParseBoard(string text)
    {
        var trimmed = text.Trim();
        var lower = trimmed.ToLowerInvariant();
        if (lower.StartsWith("rectangle", StringComparison.Ordinal) ||
            lower.StartsWith("rect", StringComparison.Ordinal))
        {
            var open = trimmed.IndexOf('{');
            var close = trimmed.LastIndexOf('}');
            var inner = open >= 0 && close > open ? trimmed[(open + 1)..close].Trim() : string.Empty;
            if (inner.Length == 0)
            {
                throw new PuzzleFormatException(
                    "board_shape: expected `rectangle{width,height}`, for example `rectangle{20,3}`");
            }

            var separator = inner.Contains(',')
                ? ','
                : inner.Contains('x') || inner.Contains('X')
                    ? 'x'
                    : inner.Contains('*')
                        ? '*'
                        : '\0';
            if (separator == '\0')
            {
                throw new PuzzleFormatException(
                    $"board_shape: `{trimmed}` is not a valid rectangle; use `rectangle{{width,height}}`");
            }

            var parts = inner.Split(separator);
            if (parts.Length != 2)
            {
                throw new PuzzleFormatException(
                    $"board_shape: `{trimmed}` has too many dimensions; expected `rectangle{{width,height}}`");
            }

            var width = ParseInt(parts[0].Trim(), "board_shape width");
            var height = ParseInt(parts[1].Trim(), "board_shape height");
            if (width <= 0 || height <= 0)
            {
                throw new PuzzleFormatException(
                    $"board_shape: rectangle{{width,height}} needs positive sizes, got {{{width},{height}}}");
            }

            return BoardModel.Rectangle(width, height);
        }

        var rows = text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');
        return BoardModel.FromAscii(rows);
    }

    private static YamlMappingNode NormalizeMapping(YamlNode node, string context)
    {
        if (node is YamlMappingNode mapping)
        {
            return mapping;
        }

        if (node is YamlSequenceNode sequence)
        {
            var merged = new YamlMappingNode();
            for (var i = 0; i < sequence.Children.Count; i++)
            {
                if (sequence.Children[i] is not YamlMappingNode item)
                {
                    throw new PuzzleFormatException(
                        $"{context}: entry {i + 1} must be a mapping (`- key: value`)");
                }

                foreach (var pair in item.Children)
                {
                    merged.Children[pair.Key] = pair.Value;
                }
            }

            return merged;
        }

        throw new PuzzleFormatException($"{context}: expected a mapping or a list of `- key: value` entries");
    }

    private static bool TryGet(YamlMappingNode map, string key, out YamlNode value)
    {
        foreach (var pair in map.Children)
        {
            if (pair.Key is YamlScalarNode scalar && scalar.Value == key)
            {
                value = pair.Value;
                return true;
            }
        }

        value = null!;
        return false;
    }

    private static YamlNode? GetAny(YamlMappingNode map, params string[] keys)
    {
        foreach (var key in keys)
        {
            if (TryGet(map, key, out var value))
            {
                return value;
            }
        }

        return null;
    }

    private static string RequireScalar(YamlNode node, string context)
    {
        if (node is YamlScalarNode scalar && scalar.Value is not null)
        {
            return scalar.Value;
        }

        throw new PuzzleFormatException($"{context}: expected a string");
    }

    private static string ShapeText(YamlNode node, string context)
    {
        if (node is YamlScalarNode scalar)
        {
            return scalar.Value ?? string.Empty;
        }

        if (node is YamlSequenceNode sequence)
        {
            var rows = new List<string>();
            for (var i = 0; i < sequence.Children.Count; i++)
            {
                rows.Add(RequireScalar(sequence.Children[i], $"{context}[{i}]"));
            }

            return string.Join('\n', rows);
        }

        throw new PuzzleFormatException($"{context}: expected a string or a list of row strings");
    }

    private static bool GetBool(YamlMappingNode map, string key, bool fallback) =>
        TryGet(map, key, out var node) ? ParseBool(RequireScalar(node, key), key) : fallback;

    private static bool GetBool(YamlMappingNode map, string key, string alias, bool fallback)
    {
        if (TryGet(map, key, out var node) || TryGet(map, alias, out node))
        {
            return ParseBool(RequireScalar(node, key), key);
        }

        return fallback;
    }

    private static bool ParseBool(string value, string context) =>
        value.Trim().ToLowerInvariant() switch
        {
            "true" or "yes" or "on" or "1" => true,
            "false" or "no" or "off" or "0" => false,
            _ => throw new PuzzleFormatException($"{context}: expected a boolean, found {value}"),
        };

    private static TriState GetTriState(YamlMappingNode map, string key, string alias)
    {
        YamlNode node;
        if (!TryGet(map, key, out node) && !TryGet(map, alias, out node))
        {
            return TriState.Inherit;
        }

        return ParseBool(RequireScalar(node, key), key) ? TriState.Allow : TriState.Forbid;
    }

    private static int ParseInt(string value, string context)
    {
        if (!int.TryParse(value.Trim(), NumberStyles.Integer, CultureInfo.InvariantCulture, out var result))
        {
            throw new PuzzleFormatException($"{context}: expected a non-negative integer, found {value}");
        }

        return result;
    }

    private static string Quote(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('"');
        foreach (var ch in value)
        {
            switch (ch)
            {
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '"':
                    builder.Append("\\\"");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\r':
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    if (char.IsControl(ch))
                    {
                        builder.Append("\\u").Append(((int)ch).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(ch);
                    }

                    break;
            }
        }

        builder.Append('"');
        return builder.ToString();
    }
}
