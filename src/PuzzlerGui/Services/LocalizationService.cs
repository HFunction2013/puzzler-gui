    public IReadOnlyList<LanguageOption> Languages { get; } = new[]
    {
        new LanguageOption("en", "English"),
        new LanguageOption("zh-CN", "简体中文"),
        new LanguageOption("zh-TW", "繁體中文"),
        new LanguageOption("ja", "日本語"),
    };

    [ObservableProperty]
    private string _currentLanguage = "en";

    public IReadOnlyDictionary<string, string> Strings => Translations[CurrentLanguage];

    public string this[string key] =>
        Strings.TryGetValue(key, out var value) ? value : Translations["en"].TryGetValue(key, out var fallback) ? fallback : key;

    public void Apply(string? languageCode)
    {
        CurrentLanguage = IsSupported(languageCode) ? languageCode! : Detect();
        OnPropertyChanged(nameof(Strings));
        OnPropertyChanged("Item[]");
    }

    public void SetLanguage(string code)
    {
        CurrentLanguage = IsSupported(code) ? code : Detect();
        OnPropertyChanged(nameof(Strings));
        OnPropertyChanged("Item[]");
    }

    public static string Detect()
    {
        var name = CultureInfo.CurrentUICulture.Name;
        if (name.StartsWith("zh-Hant", StringComparison.OrdinalIgnoreCase) ||
            name is "zh-TW" or "zh-HK" or "zh-MO")
        {
            return "zh-TW";
        }

        if (name.StartsWith("zh", StringComparison.OrdinalIgnoreCase))
        {
            return "zh-CN";
        }

        if (name.StartsWith("ja", StringComparison.OrdinalIgnoreCase))
        {
            return "ja";
        }

        return "en";
    }

    private static bool IsSupported(string? code) =>
        !string.IsNullOrWhiteSpace(code) && Translations.ContainsKey(code);

